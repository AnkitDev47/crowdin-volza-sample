import React, { useState } from 'react';
import { useTranslation } from 'react-i18next';
import { useHistory } from 'react-router-dom';
import { userProfile } from '../data';

// Mirrors frontend.app.volza.com WelcomePage + WelcomePageGrid; every visible string goes through t().
const pageItems = [
	['AutoGenerated', 'icon-person-autogenerated'], ['SignUp', 'icon-person-key'], ['FavouriteShipments', 'my-download-1'],
	['ManageAccount', 'icon-person', '/myprofile'], ['InviteTeam', 'share-demo-icon'], ['Database', 'navigation-icon'],
	['HowToSearch', 'magic-serch'], ['PartialView', 'magic-serch'], ['FiltersAndFields', 'magic-serch'],
	['MyWorkSpaces', 'workspace-icon'], ['ContactDetails', 'my-download'], ['CompanyFullProfile', 'company-icon'],
	['CompaniesTabANDSettingAlerts', 'company-icon'], ['DashboardAndGraph', 'dashboard-icon'], ['SumamaryAndAnalysis', 'summary-icon'],
	['HotProducts', 'trending-product'], ['HotCompanies', 'trending-companies'], ['BuyerSupplierCRMModule', 'universalSearchIcon'],
	['UniversalSearch', 'universalSearchIcon'], ['TicketAndChat', 'ticket-chat-icon']
];
const rightItems = [
	['HowToVideo', 'video_icon_outline'], ['FAQ', 'icon-questionmark-outline'],
	['RemoteSupport', 'icon-remotesupport'], ['ScheduleDemo', 'icon-headphones']
];
const searchTypes = ['hscode', 'HS4Or8', 'product', 'company', 'importer', 'exporter'];

const greetingKey = () => {
	const hour = new Date().getHours();
	return hour >= 5 && hour < 12 ? 'welcome.goodMorning' : hour < 17 && hour >= 12 ? 'welcome.goodAfternoon' : 'welcome.goodEvening';
};

export default function Welcome() {
	const { t, i18n } = useTranslation();
	const history = useHistory();
	const [searchType, setSearchType] = useState('product');
	const [activeItem, setActiveItem] = useState('');
	const { AccountSummary, activeSubscriptionDetails: [plan] } = userProfile;
	const expiresOn = new Intl.DateTimeFormat(i18n.resolvedLanguage, { dateStyle: 'long' }).format(new Date(plan.Validity));

	return <div className="welcome-page">
		<article className="form-simple-search col-sm-12 col-md-12 col-lg-12">
			<div className="universalSearch color-grey welcome-tab">
				<div className="row">
					<div className="header-text"><div>{t('welcome.searchHeading')}</div></div>
					{searchType === 'hscode' && <div className="hs-code-text">{t('welcome.hsCodeNote')}</div>}
					<div id="search-form" className="mt-1 col-lg-12">
						<div className="universalsearch-parent-container">
							<form className="welcome-tab-form" onSubmit={e => e.preventDefault()}>
								<div className="universalsearch-inputgroup">
									<select className="form-control customClassic seacrh-type-selectHome input-width" aria-label={t('welcome.searchBy')}
										value={searchType} onChange={e => setSearchType(e.target.value)}>
										{searchTypes.map(type => <option value={type} key={type}>{t(`welcome.searchType.${type}`)}</option>)}
									</select>
									<div className="welcome-tab-input-group">
										<input className="react-tags__search-input customTagsInput" placeholder={t(`welcome.placeholder.${['hscode', 'HS4Or8'].includes(searchType) ? searchType : 'product'}`)} aria-label={t('welcome.search')} />
										<span className="input-group-btn">
											<button type="submit" className="btn btn-default searchButton" aria-label={t('welcome.search')}><i className="fa fa-search search-icon" /></button>
										</span>
									</div>
								</div>
								<div className="universalsearch-hslocator universalsearch-hslocator-welcome-page">
									<button type="button" hidden={!['hscode', 'HS4Or8'].includes(searchType)} className="btn btn-successhslocator">{t('welcome.hsLocator')}</button>
								</div>
							</form>
						</div>
					</div>
				</div>
			</div>
		</article>
		<div className="span-container">
			<span>{t('welcome.whatToDo', { greeting: t(greetingKey()), name: AccountSummary.FirstName })}</span>
		</div>
		<article className="form-simple-search cont-pd col-sm-12 col-md-12 col-lg-12">
			<div className="bg-color1">
				<div className="brdr-box plan-expiry-block">
					<div className="row-margin row-padding row">
						<i className="fa fa-exclamation-triangle" />&nbsp;{t('welcome.planExpiring')}&nbsp;<i className="fa fa-exclamation-triangle" />&nbsp;
						<button className="btn-custom-renew"><i className="fa fa-refresh" />&nbsp; {t('welcome.renewNow')}</button>
					</div>
				</div>
				{pageItems.map(([name, icon, path], index) => <div key={name} className={`${index ? 'row-margin-top' : ''} brdr-box color-black-imp`}>
					<div className="row row-margin row-padding">
						<div className="col-md-3">
							<div className="row display-flex align-items-center">
								<div className="col-md-1 icon-margin icon-margin-main"><div className={'icon-margin ' + icon} /></div>
								<div className="col-md-10 cont-33-content icon-margin icon-margin-main2">
									<div className="row blueBold icon-margin df-panel-tools ft-weight-400" onClick={() => path && history.push(path)}>{t(`welcome.item.${name}`)}</div>
									{name === 'ManageAccount' && <div className="row textpart icon-margin plan-details-span">
										<span>{plan.PlanName} |<span className="expires"> {t('welcome.expiresOn', { date: expiresOn })}</span></span>
									</div>}
								</div>
							</div>
						</div>
						<div className="col-md-10 fright icon-margin ft-weight-400">
							<div className="row d-flex align-items-center flex-end-welcome">
								{rightItems.map(([key, rightIcon], ind) => <div key={key}>
									<div className="col-md-6 icon-margin df-panel-tools icon-margin-left welcome-items" onClick={() => setActiveItem(`${index}_${ind}`)}>
										<div className={rightIcon} />
										<span className={activeItem === `${index}_${ind}` ? 'blueBold' : ''}>{t(`welcome.action.${key}`)}</span>
									</div>
								</div>)}
							</div>
						</div>
					</div>
				</div>)}
			</div>
			<div className="btn-align">
				<button className="schedule df-panel-tools" type="button">{t('welcome.scheduleDemo')}</button>
				<div className="display-flex">
					<label className="welcome-tab-help help-welcome-tab">{t('welcome.needHelp')}</label>
				</div>
			</div>
		</article>
	</div>;
}
